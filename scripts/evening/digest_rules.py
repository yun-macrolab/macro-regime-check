def _inside(a, b):
    """낱말 a의 이름이 다른 낱말 b의 이름 안에 토막째 들어 있는가 — '연준' ⊂ '연준 의사록', 'AI' ⊂ 'AI Capex'.
    글자만 겹치는 것('인플레'와 '기대인플레')은 세지 않는다."""
    x, y = a.split(), b.split()
    return a != b and any(y[i:i + len(x)] == x for i in range(len(y) - len(x) + 1))


# 넓은 낱말 — 다른 사전 낱말의 이름에 토막째 든 낱말(연준 ⊂ 연준 의사록 · AI ⊂ AI Capex · 금리 ⊂ 국고채 금리 …). 같은 등급 안에서
# 뒤에 놓고(_ORDER), 좁은 낱말이 곁에 있으면 뺀다(narrow). 뜻이 갈리는 짝(캐리와 엔 캐리 · 단기자금과 국내 단기자금 · 경기와 중국 경기)과
# A급(금통위와 금통위 의사록은 서로 다른 일이다)은 넣지 않는다
WIDE = frozenset(("연준", "한은", "AI", "금리", "커브", "국채 입찰", "실적"))
_ORDER = {e["term"]: (GRADES.index(e["grade"]), e["term"] in WIDE, e["term"]) for e in LEXICON}


def by_grade(terms):
    """낱말들을 등급 → (넓은 낱말은 뒤) → 가나다 순으로(겹친 것은 한 번). 공개본의 낱말 목록은 글에 나온 순서가 아니라 이 순서로만
    나간다 — 낱말을 늘어놓은 것이 글의 요약 문장처럼 읽히지 않게."""
    return sorted(set(terms), key=_ORDER.__getitem__)


def by_count(counts):
    """{낱말: 쓴 채널 수} → [(낱말, 수)] 곳 수가 많은 순 → 등급 → (넓은 낱말은 뒤) → 가나다."""
    return sorted(counts.items(), key=lambda kv: (-kv[1], *_ORDER[kv[0]]))


def narrow(terms, among=()):
    """낱말들에서, 더 좁은 낱말(이름이 그 낱말을 토막째 품은 것)이 terms나 among에 있는 넓은 낱말을 뺀다 — '연준 의사록'이 있으면
    '연준'을, 'AI Capex'가 있으면 'AI'를. 순서는 그대로 둔다."""
    pool = set(terms) | set(among)
    return [t for t in terms if not (t in WIDE and any(_inside(t, o) for o in pool))]


