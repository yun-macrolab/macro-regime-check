def size_of(text):
    """글 → 길이 구간 이름. 글자 수 자체는 남기지 않는다."""
    n = len(norm_text(text))
    return SIZES[0] if n < TH["size_short"] else SIZES[2] if n >= TH["size_long"] else SIZES[1]


def gloss_of(term):
    """낱말의 풀이 {"term", "text", "url"} — 풀이가 없는 낱말이면 None."""
    got = GLOSS.get(term) if isinstance(term, str) else None
    return {"term": term, "text": got[0], "url": got[1]} if got else None


def glosses(terms):
    """낱말들 가운데 풀이가 있는 것 → 풀이 목록. 한 번씩, 사전에 실린 순서로."""
    return [gloss_of(t) for t in sorted({t for t in terms if t in GLOSS}, key=_PLACE.__getitem__)]


def _compile(entries):
    return tuple((e["term"] if "term" in e else e["result"], tuple(re.compile(p, _FLAGS) for p in e["pats"]),
                  tuple(re.compile(p, _FLAGS) for p in e["not"])) for e in entries)


def _hits(compiled, text):
    """[(낱말, 시작, 끝)] — 제외 패턴과 겹치는 자리는 뺀다."""
    out = []
    for word, pats, veto in compiled:
        no = [m.span() for p in veto for m in p.finditer(text)]
        for p in pats:
            for m in p.finditer(text):
                a, b = m.span()
                if a < b and not any(a < nb and na < b for na, nb in no):
                    out.append((word, a, b))
    return out


def _kept(compiled, t, skip=()):
    """정리된 글 t에서 남기는 자리 [(낱말, 시작, 끝)] — 다른 낱말의 더 긴 자리에 완전히 들어간 자리는 버린다. skip의 낱말은 없는 셈 친다."""
    kept = []
    for word, a, b in sorted(_hits(compiled, t), key=lambda h: (h[1] - h[2], h[1], h[0])):
        if word not in skip and not any(ka <= a and b <= kb and kw != word for kw, ka, kb in kept):
            kept.append((word, a, b))
    return kept


def _earliest(kept, key):
    """남긴 자리들(_kept) → 낱말마다 가장 이른 자리 하나를 자리순으로."""
    first = {}
    for word, a, _ in kept:
        first[word] = min(a, first.get(word, a))
    return [{key: w, "pos": p} for w, p in sorted(first.items(), key=lambda kv: (kv[1], kv[0]))]


_LEX_C = _compile(LEXICON)
# 뜻이 넓은 낱말 → 같은 글에 있으면 그 낱말을 대신하는 좁은 낱말들. 나라를 밝힌 입찰 글에 '국채 입찰'이 겹쳐 붙지 않게 한다
_GENERIC = {"국채 입찰": ("국고채 입찰", "미 국채 입찰")}


def _lex_kept(text):
    """글의 사전 낱말 자리 [(낱말, 시작, 끝)] — 좁은 낱말이 같은 글에 있으면 넓은 낱말(_GENERIC)은 없는 셈 치고 다시 고른다
    (넓은 낱말의 자리에 가려졌던 다른 낱말이 되살아나게)."""
    t = norm_text(text)
    kept = _kept(_LEX_C, t)
    have = {w for w, _, _ in kept}
    skip = {wide for wide, narrow in _GENERIC.items() if wide in have and have.intersection(narrow)}
    return _kept(_LEX_C, t, skip) if skip else kept


def match_terms(text):
    """글에서 사전 낱말을 찾는다 → [{"term", "pos"}] 자리순."""
    return _earliest(_lex_kept(text), "term")


def term_hits(text):
    """글에서 사전 낱말의 자리 전부 → [(낱말, 시작, 끝)] 자리순. 같은 낱말이 여러 번 나오면 여러 번 준다."""
    kept = set(_lex_kept(text))
    inside = lambda h: any(o != h and o[0] == h[0] and o[1] <= h[1] and h[2] <= o[2] for o in kept)     # 같은 낱말의 더 긴 자리 안
    return sorted((h for h in kept if not inside(h)), key=lambda h: (h[1], h[2], h[0]))


def named_before(hits, at, reach=None):
    """숫자 자리 at 앞의 가장 가까운 A·B급 낱말 — 낱말의 끝에서 reach자(기본 num_term_chars) 안일 때만(숫자를 품은 낱말 자리도 센다).
    hits = term_hits의 것. 없으면 None — 멀리 있는 낱말이나 묶음의 대표 낱말을 대신 붙이지 않는다."""
    reach = TH["num_term_chars"] if reach is None else reach
    near = [(a, b, w) for w, a, b in hits if a < at and at - b <= reach and TERMS[w]["grade"] in ("A", "B")]
    return max(near)[2] if near else None


def grade_of(term):
    return TERMS[term]["grade"]


def best_grade(terms):
    """낱말들 가운데 가장 높은 등급. 없으면 None."""
    grades = [TERMS[t]["grade"] for t in terms]
    return min(grades, key=GRADES.index) if grades else None


def has_tag(terms, tag):
    return any(tag in TERMS[t]["tags"] for t in terms)


