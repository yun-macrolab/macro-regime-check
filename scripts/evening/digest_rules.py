def phrase(code, **slots):
    """고정 문구를 만든다. 빈칸은 숫자(n)뿐이다."""
    n = slots.get("n")
    if set(slots) - {"n"} or ("{n}" in PHRASES[code]) != (type(n) is int and 0 < n < 1000):
        raise ValueError("고정 문구의 빈칸은 1~999의 정수 n 하나뿐")
    return PHRASES[code].format(**slots)


def is_phrase(s):
    return isinstance(s, str) and any(rx.fullmatch(s) for rx in _PHRASE_RES)


