def norm_text(s):
    """NFKC로 맞추고 보이지 않는 문자(폭 없는 공백 등)를 뺀 뒤 공백 묶음(줄바꿈 포함)을 공백 하나로."""
    s = unicodedata.normalize("NFKC", s if isinstance(s, str) else "")
    return " ".join("".join(c for c in s if unicodedata.category(c) != "Cf").split())


