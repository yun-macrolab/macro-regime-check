_PARTICLES = "을를이가은는의에로과와도만대씩나인라까부으"      # 한글 단위 뒤에 와도 되는 조사의 첫 글자
_UNIT_ALT = "|".join(f"(?P<u{i}>{pat})" for i, (_, pat) in enumerate(UNITS))
# 숫자를 '잡는' 자리는 [0-9]만 — \d는 다른 문자의 숫자 글자도 받아 그 글자가 공개본에 실린다. 맨 앞의 살핌은 \d 그대로 둔다
# (다른 문자의 숫자 바로 뒤에서 새 숫자가 시작되지 않게)
_NUM_RE = re.compile(r"(?<![\d.,A-Za-z])(?P<int>[0-9]{1,3}(?:,[0-9]{3})+|[0-9]{1,7})(?P<frac>\.[0-9]{1,3})?\s?(?:" + _UNIT_ALT + r")"
                     r"(?![A-Za-z%])(?:(?<![가-힣])|(?![가-힣])|(?=[" + _PARTICLES + "]))")
NUM_OUT_RE = re.compile(r"^-?(?:0|[1-9][0-9]{0,6})(?:\.[0-9]{0,2}[1-9])?(?:" + "|".join(map(re.escape, UNIT_NAMES)) + r")$")


def _canon(m, text):
    whole = str(int(m.group("int").replace(",", "")))
    frac = (m.group("frac") or "").rstrip("0").rstrip(".")
    unit = next(UNITS[i][0] for i in range(len(UNITS)) if m.group(f"u{i}") is not None)
    a = m.start()
    minus = a > 0 and text[a - 1] in "-−" and (a < 2 or not (text[a - 2].isalnum() or text[a - 2] in "%)"))
    return ("-" if minus and (whole != "0" or frac) else "") + whole + frac + unit


def find_nums(text):
    """글에서 숫자+허용 단위를 찾는다 → [{"v", "pos"}] 자리순, 같은 값은 가장 이른 자리 하나."""
    t, first = norm_text(text), {}
    for m in _NUM_RE.finditer(t):
        v = _canon(m, t)
        if NUM_OUT_RE.fullmatch(v):
            first.setdefault(v, m.start())
    return [{"v": v, "pos": p} for v, p in sorted(first.items(), key=lambda kv: (kv[1], kv[0]))]


def is_num(s):
    return isinstance(s, str) and bool(NUM_OUT_RE.fullmatch(s))


def num_unit(v):
    """맞춘 꼴의 숫자 → (값 문자열, 단위)."""
    m = re.match(r"^(-?[0-9.]+)(.+)$", v) if is_num(v) else None
    if not m:
        raise ValueError("숫자+단위 꼴이 아님")
    return m.group(1), m.group(2)


def is_quote(v):
    """시세 수준으로 보이는 숫자인가 — 소수 셋째 자리 %(금리 수준), 작은 bp·소수 bp(변동 폭), 원·달러(환율·유가)."""
    n, unit = num_unit(v)
    decimals = len(n.split(".")[1]) if "." in n else 0
    if unit == "%":
        return decimals >= TH["quote_pct_decimals"]
    if unit == "bp":
        return decimals > 0 or abs(float(n)) < TH["quote_bp_below"]
    return unit in QUOTE_UNITS


def solo_num_ok(v):
    """한 곳만 쓴 숫자로 실어도 되는가(속보형·개인 단독 줄) — 시세 수준(is_quote), 자릿수가 row_digits_max를 넘는 숫자(전화번호 같은
    긴 숫자가 한 칸에 실리지 않게), row_pp_max를 넘는 %p(단위를 잘못 적은 글)는 싣지 않는다."""
    n, unit = num_unit(v)
    digits = sum(c.isdigit() for c in n)
    return not is_quote(v) and digits <= TH["row_digits_max"] and not (unit == "%p" and abs(float(n)) > TH["row_pp_max"])


