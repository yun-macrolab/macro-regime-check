def drop_code(text, n_links=0):
    """먼저 버리는 글이면 사유 코드, 아니면 None. 광고·모집은 늘 버리고, 코인·종목 공시는 A·B급 낱말이 없을 때만 버린다.
    주소뿐인 글(수집이 주소 글자를 본문에서 빼 본문이 빈다)은 링크가 있으면 둔다 — 주소·카드 열쇠로 묶일 수 있게."""
    t = norm_text(text)
    if not t:
        return None if n_links else "empty"
    if len(t) < TH["min_chars"] and not n_links:
        return "short"
    if any(p.search(t) for p in _AD):
        return "ad"
    if best_grade([h["term"] for h in match_terms(t)]) in ("A", "B"):
        return None
    if any(p.search(t) for p in _COIN):
        return "coin"
    return "filing" if any(p.search(t) for p in _FILING) else None
